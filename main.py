import pandas as pd

students_df = pd.read_csv("students.csv")

import numpy as np

subjects = ["Python", "SQL", "HTML", "CSS", "JavaScript"]

def calculate_grade(average):
    if average >= 90:
        return "A+"
    elif average >= 80:
        return "A"
    elif average >= 70:
        return "B"
    elif average >= 60:
        return "C"
    elif average >= 40:
        return "D"
    else:
        return "F"


marks = students_df[subjects].to_numpy()

students_df["Total"] = np.sum(marks, axis=1)
students_df["Average"] = np.mean(marks, axis=1).round(2)
grades = []
results = []

for _, student in students_df.iterrows():
    grades.append(calculate_grade(student["Average"]))

    passed_subjects = all(student[subject] >= 40 for subject in subjects)
    attendance_ok = student["Attendance"] >= 75

    if passed_subjects and attendance_ok:
        results.append("Pass")
    else:
        results.append("Fail")

students_df["Grade"] = grades
students_df["Result"] = results

performance_df = students_df[
    ["Student_ID", "Name", "Total", "Average", "Grade", "Result"]
]

print("STUDENT PERFORMANCE")
display(performance_df)

